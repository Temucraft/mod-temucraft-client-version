#!/usr/bin/env python3
"""Writes Interface/FrameXML/Temucraft/TemucraftReputationData.lua from a Faction.dbc (3.3.5, 57 fields).

The reputation window (TemucraftReputation.lua) groups factions under expansion headers. 3.3.5's GetFactionInfo
gives no faction id, so the window knows factions by name: the server (mod-temucraft-renown) sends the names in the
player's locale, and this file has the English ones for when it doesn't. It also says which group each of our own
factions goes in (the stock ones go under their stock expansion header).

Get the newest Faction.dbc of the release patches first (patch-T.MPQ wins over patch-5.MPQ), e.g.
    python3 _tools/mpqtool3.py --get "5) Release/patches/patch-T.MPQ" "DBFilesClient\\Faction.dbc" > Faction.dbc
    python3 client/gen_reputation_data.py Faction.dbc
"""
import os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "Interface", "FrameXML", "Temucraft", "TemucraftReputationData.lua")

# the stock expansion headers
ROOTS = {1118: "classic", 980: "tbc", 1097: "wotlk"}
# our own factions: id -> group (anything 2300-2399 is Lost Lands, from the Crazy repack's salvage)
GROUPS = {
    1133: "cata", 1134: "cata",                       # Bilgewater Cartel, Gilneas
    1352: "mists", 1353: "mists",                     # Huojin / Tushui Pandaren
    2233: "crafting", 2234: "crafting",               # Azeroth Commerce Authority, Durotar Supply and Logistics
}
ALLIED = [1168, 1171, 1191, 1193, 1195, 1261, 1263, 1311, 1313, 1828, 1859, 2103, 2158, 2160, 2165, 2170]
for i in ALLIED:
    GROUPS[i] = "allied"


def group_of(fid):
    if fid in GROUPS:
        return GROUPS[fid]
    if 2300 <= fid <= 2399:
        return "lostlands"
    return None


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    d = open(sys.argv[1], "rb").read()
    magic, n, fields, size, ssize = struct.unpack_from("<4s4I", d)
    if magic != b"WDBC" or fields != 57:
        sys.exit("not a 3.3.5 Faction.dbc")
    strings = 20 + n * size

    def text(o):
        end = d.index(b"\0", strings + o)
        return d[strings + o:end].decode("utf-8", "replace")

    names, groups = [], []
    for i in range(n):
        r = struct.unpack_from("<%di" % fields, d, 20 + i * size)
        fid, index, name = r[0], r[1], text(r[23])
        if index < 0 or not name:
            continue
        names.append((name, fid))
        g = group_of(fid)
        if g:
            groups.append((fid, g, name))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by client/gen_reputation_data.py from Faction.dbc: do not edit by hand.\n")
        f.write("-- names: the English name of every faction with a reputation (the window's fallback when the server\n")
        f.write("-- doesn't send them); groups: our own factions' group; roots: the stock expansion headers.\n")
        f.write("TemucraftReputationData = {\n\tnames = {\n")
        for name, fid in sorted(names):
            f.write("\t\t[%s] = %d,\n" % (lua(name), fid))
        f.write("\t},\n\tgroups = {\n")
        for fid, g, name in sorted(groups):
            f.write("\t\t[%d] = %s, -- %s\n" % (fid, lua(g), name))
        f.write("\t},\n\troots = { ")
        f.write(", ".join("[%d] = %s" % (k, lua(v)) for k, v in sorted(ROOTS.items())))
        f.write(" },\n};\n")
    print(f"{OUT}: {len(names)} factions, {len(groups)} in our own groups")


if __name__ == "__main__":
    main()
